// Generates deploy/cloudfront-function.js from src/data/redirects.mjs.
// Runs automatically after `npm run build` (see package.json "postbuild").
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { legacyRedirects } from '../src/data/redirects.mjs';

const out = fileURLToPath(new URL('../deploy/cloudfront-function.js', import.meta.url));
mkdirSync(fileURLToPath(new URL('../deploy/', import.meta.url)), { recursive: true });

// Lowercased keys: legacy URLs were case-insensitive in practice for visitors typing them.
const map = Object.fromEntries(Object.entries(legacyRedirects).map(([k, v]) => [k.toLowerCase(), v]));

const src = `// GENERATED by scripts/build-cloudfront-function.mjs — do not edit by hand.
// CloudFront Functions runtime 2.0, viewer-request event, attached to the default (*) behavior.
// 1. Canonical host: saasnova.ai -> https://www.saasnova.ai (301)
// 2. Legacy URLs (.html pages, old paths) -> new URLs (301)
// 3. Clean URLs: /programs/ignite -> /programs/ignite/index.html (internal rewrite)
// 4. Trailing slash: /about/ -> /about (301), matching canonical tags
var REDIRECTS = ${JSON.stringify(map, null, 2)};

function redirect(location) {
  return { statusCode: 301, statusDescription: 'Moved Permanently', headers: {
    location: { value: location }, 'cache-control': { value: 'public, max-age=86400' } } };
}

function qs(querystring) {
  var parts = [];
  for (var k in querystring) {
    var v = querystring[k];
    if (v.multiValue) { for (var i = 0; i < v.multiValue.length; i++) parts.push(k + '=' + v.multiValue[i].value); }
    else parts.push(v.value === '' ? k : k + '=' + v.value);
  }
  return parts.length ? '?' + parts.join('&') : '';
}

function handler(event) {
  var req = event.request;
  var host = req.headers.host ? req.headers.host.value.toLowerCase() : '';
  var uri = req.uri;
  var q = qs(req.querystring);

  if (host === 'saasnova.ai') return redirect('https://www.saasnova.ai' + uri + q);

  // API and static assets pass straight through.
  if (uri.indexOf('/api/') === 0 || uri.indexOf('/_assets/') === 0) return req;

  var key = uri;
  try { key = decodeURIComponent(uri); } catch (e) {}
  key = key.toLowerCase().replace(/\\/index\\.html$/, '').replace(/\\.html$/, '');
  if (key.length > 1 && key.charAt(key.length - 1) === '/') key = key.slice(0, -1);
  if (key === '') key = '/';

  if (REDIRECTS[key] !== undefined) return redirect(REDIRECTS[key] + q);

  // Direct requests for directory index objects: /about/index.html -> /about
  if (/\\/index\\.html$/i.test(uri)) return redirect(key + q);

  // Trailing slash -> no trailing slash (except root).
  if (uri.length > 1 && uri.charAt(uri.length - 1) === '/') return redirect(uri.slice(0, -1) + q);

  // /foo.html that is not a legacy page: strip the extension.
  if (/\\.html$/.test(uri) && uri !== '/404.html') return redirect(uri.replace(/\\.html$/, '') + q);

  // Extensionless path -> directory index object.
  var last = uri.split('/').pop();
  if (last.indexOf('.') === -1) req.uri = (uri === '/' ? '' : uri) + '/index.html';
  return req;
}
`;
writeFileSync(out, src);
console.log(`deploy/cloudfront-function.js written (${Object.keys(map).length} redirects)`);
